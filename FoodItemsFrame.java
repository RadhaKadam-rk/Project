    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed

        String name = txtItemName.getText().trim();
        String priceText = txtPrice.getText().trim();
        boolean status = cmbAvailability.getSelectedItem().toString().equals("Available");

        if (name.isEmpty() || priceText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Fields cannot be blank!");
            return;
        }

        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
            String s="jdbc:mysql://localhost:3306/smart_cafeteria";
            Connection con = DriverManager.getConnection(s,"root","YOUR_PASSWORD_HERE");
            if (con == null) {
                JOptionPane.showMessageDialog(this, "Database connection failed!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            String query = "INSERT INTO Food_Items (item_name, price, availability_status) VALUES (?, ?, ?)";
            PreparedStatement pst = con.prepareStatement(query);
            pst.setString(1, name);
            pst.setDouble(2, Double.parseDouble(priceText));
            pst.setBoolean(3, status);

            pst.executeUpdate();
            JOptionPane.showMessageDialog(this, "Food Item inserted safely into catalog!");
            loadFoodItemsTable();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Database Write Error: " + e.getMessage());
        }    // TODO add your handling code here:
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        int selectedRow = tableFoodItems.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Select a food item to drop!");
            return;
        }

        int id = Integer.parseInt(tableFoodItems.getValueAt(selectedRow, 0).toString());
        int action = JOptionPane.showConfirmDialog(this, "Remove item from menu completely?", "Warning", JOptionPane.YES_NO_OPTION);

        if (action == JOptionPane.YES_OPTION) {
            try  {
                Class.forName("com.mysql.cj.jdbc.Driver");
                String s="jdbc:mysql://localhost:3306/smart_cafeteria";
                Connection con = DriverManager.getConnection(s,"root","YOUR_PASSWORD_HERE");
                if (con == null) {
                    JOptionPane.showMessageDialog(this, "Database connection failed!", "Error", JOptionPane.ERROR_MESSAGE);
                    return;
                }
                String query = "DELETE FROM Food_Items WHERE item_id = ?";
                PreparedStatement pst = con.prepareStatement(query);
                pst.setInt(1, id);
                pst.executeUpdate();

                JOptionPane.showMessageDialog(this, "Dish removed from active operations database.");
                loadFoodItemsTable();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "SQL Drop Exception: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed

        // TODO add your handling code here:
        int selectedRow = tableFoodItems.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please choose an entry to edit from the database table rows.");
            return;
        }

        int id = Integer.parseInt(tableFoodItems.getValueAt(selectedRow, 0).toString());
        String name = txtItemName.getText().trim();
        double price = Double.parseDouble(txtPrice.getText().trim());
        boolean status = cmbAvailability.getSelectedItem().toString().equals("Available");

        try {
            Class.forName("com.mysql.cj.jdbc.Driver");
            String s="jdbc:mysql://localhost:3306/smart_cafeteria";
            Connection con = DriverManager.getConnection(s,"root","YOUR_PASSWORD_HERE");
            if (con == null) {
                JOptionPane.showMessageDialog(this, "Database connection failed!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            String query = "UPDATE Food_Items SET item_name = ?, price = ?, availability_status = ? WHERE item_id = ?";
            PreparedStatement pst = con.prepareStatement(query);
            pst.setString(1, name);
            pst.setDouble(2, price);
            pst.setBoolean(3, status);
            pst.setInt(4, id);

            pst.executeUpdate();
            JOptionPane.showMessageDialog(this, "Database profile modified successfully!");
            loadFoodItemsTable();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Execution Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

