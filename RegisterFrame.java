    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        // TODO add your handling code here:
        String idStr = txtNewUserId.getText().trim();
        String name = txtNewName.getText().trim();
        String email = txtNewEmail.getText().trim();
        String phone = txtNewPhone.getText().trim();
        String userType = cmbNewUserType.getSelectedItem().toString();

        // 2. Form Validation: Make sure they filled everything out
        if (idStr.isEmpty() || name.isEmpty() || email.isEmpty() || phone.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill out all fields on the form!", "Blank Inputs", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int userId = Integer.parseInt(idStr); // Ensure ID is numbers only

            // 3. Establish the connection line channel to MySQL
            Class.forName("com.mysql.cj.jdbc.Driver");
            String url = "jdbc:mysql://localhost:3306/smart_cafeteria";
            Connection con = DriverManager.getConnection(url, "root", "YOUR_PASSWORD_HERE");

            // 4. Send fields down to the table. Starting wallet balance defaults to 500.00 automatically
            String query = "INSERT INTO Users (user_id, name, email, phone_number, user_type, digital_wallet_balance) VALUES (?, ?, ?, ?, ?, 500.00)";
            PreparedStatement pst = con.prepareStatement(query);
            pst.setInt(1, userId);
            pst.setString(2, name);
            pst.setString(3, email);
            pst.setString(4, phone);
            pst.setString(5, userType);

            int executionResult = pst.executeUpdate();
            if (executionResult > 0) {
                JOptionPane.showMessageDialog(this, "Success! Account successfully created for " + name + ".\nYou can now login using ID: " + userId, "Registration Complete", JOptionPane.INFORMATION_MESSAGE);

                // Redirect them instantly back to the Login window
                new LoginFrame().setVisible(true);
                this.dispose();
            }
            con.close();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "User ID must contain numbers only!", "Formatting Error", JOptionPane.ERROR_MESSAGE);
        } catch (java.sql.SQLIntegrityConstraintViolationException e) {
            // Triggers if someone tries to reuse a UserID, Email, or Phone already taken
            JOptionPane.showMessageDialog(this, "This User ID, Email, or Phone number is already taken!", "Account Exists", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Database error encountered: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnRegisterActionPerformed

